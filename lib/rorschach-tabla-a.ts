/**
 * La Tabla A del Rorschach: qué se ve en cada área y con qué calidad formal.
 *
 * Desde el 15/10/2026 las listas son las tablas argentinas de Lunazzi: H. A.
 * Lunazzi (2019), *Tablas argentinas de calidad formal (FQ) en 1179 no
 * pacientes*, Facultad de Psicología, UNLP, capítulo 8, páginas 137 a 202. Lo
 * decidió Lorena. El libro parte de la Tabla A de Exner y le suma las
 * respuestas de la muestra argentina y los cambios de calidad, así que
 * reemplaza la lista entera. Se leyeron del PDF con un guion; el guion, lo
 * leído y la lista anterior de Exner están en `camposhr-privado/rorschach-lunazzi/`.
 *
 * Lo que se dejó como estaba:
 *   · VII D6 y VIII D4 siguen con la lista de Exner: el libro tiene errores
 *     en esas dos áreas, consultados a la UNLP el 15/10/2026.
 *   · El asterisco de respuesta nueva no se copia. Las flechas de calidad
 *     cambiada sí (↑, ↓, ↑↑, ↓↓): van al final del renglón, como en el libro,
 *     y las pidieron las psicólogas.
 *   · Las áreas, la popular y los puntajes Z, que el libro trae iguales.
 *
 * Hasta esa fecha la lista era la del cuadernillo de Exner que usaban las
 * evaluadoras, transcripta a mano (fotos en `~/Desktop/Entrevistador`).
 *
 * Cada entrada se escribe igual que en el libro, para poder auditarla renglón
 * contra renglón: primero la calidad formal, después la posición si la lleva, y
 * después la respuesta.
 *
 *   'o antenas'            → calidad o, lámina derecha
 *   'u< matorral'          → calidad u, lámina de costado
 *   'ov árbol'             → calidad o, lámina invertida
 *
 * La posición importa: la misma respuesta en la misma área cambia de calidad
 * según cómo esté la lámina. Como las láminas se administran en pantalla y no
 * se giran, `entradasDe()` deja fuera por defecto todo lo que solo vale girado.
 * El dato se guarda igual, para el día que se pueda girar.
 */

export type CalidadFormal = 'o' | 'u' | '-' | '+';
export type Posicion = 'v' | '<' | '>';

export type Entrada = {
  /** La respuesta, como figura en el libro. */
  respuesta: string;
  calidad: CalidadFormal;
  /** Cómo tiene que estar la lámina. Sin esto, derecha. */
  posicion?: Posicion;
  /**
   * Cuánto cambió la calidad respecto de la Tabla A de Exner, con las flechas
   * del libro de Lunazzi: ↑ o ↓ un nivel, ↑↑ o ↓↓ dos. Sin esto, igual que en
   * Exner o respuesta nueva. Va aparte de `respuesta` porque ese texto es el
   * que se guarda en el protocolo.
   */
  cambio?: Cambio;
};

export type Cambio = '↑' | '↓' | '↑↑' | '↓↓';

/** Los cuatro puntajes de organización de una lámina. */
export type PuntajesZ = { ZW: number; ZA: number; ZD: number; ZS: number };

export type Lamina = {
  /** La respuesta popular, y en qué área se da. */
  /**
   * La respuesta popular y dónde vale.
   *
   * Son varias áreas en cuatro láminas: en la IV la figura humana es popular
   * tanto en W como en D7, y en la VII la cabeza humana vale en D9 y también en
   * D1, D2 o Dd22. Con una sola área, la popular de esas láminas se perdía en
   * la mitad de los casos.
   */
  popular: { areas: string[]; respuestas: string[] };
  /** Las áreas, en el orden en que las presenta el libro. */
  areas: Record<string, string[]>;
};

